<?php

declare(strict_types=1);

namespace Usamamuneerchaudhary\Slipway\Local;

use InvalidArgumentException;
use Usamamuneerchaudhary\Slipway\Drivers\PhpBootstrap;
use Usamamuneerchaudhary\Slipway\Model\Job;
use Usamamuneerchaudhary\Slipway\Model\Pipeline;
use Usamamuneerchaudhary\Slipway\Model\Service;
use Usamamuneerchaudhary\Slipway\Model\Step;
use Usamamuneerchaudhary\Slipway\Model\StepType;
use Usamamuneerchaudhary\Slipway\Support\Shell;

/**
 * Turns a compiled pipeline into a bash script that runs one stage locally in Docker.
 */
final class LocalPipelineScript
{
    private const string PAUSE_IMAGE = 'busybox:1.36';

    /**
     * @param  array{options?:array<string,mixed>,raw?:array<string,mixed>}  $driverConfig
     * @param  array{defaultStage?:string,defaultPhp?:string,includeDeploy?:bool}  $settings
     */
    public function generate(Pipeline $pipeline, string $driver, array $driverConfig, array $settings = []): string
    {
        $options = $driverConfig['options'] ?? [];
        $raw = $driverConfig['raw'] ?? [];
        if (! is_array($options) || ! is_array($raw)) {
            throw new InvalidArgumentException("{$driver}: options and raw must be arrays.");
        }

        $includeDeploy = $settings['includeDeploy'] ?? false;
        $jobsByStage = $this->runnableJobsByStage($pipeline, $includeDeploy);
        if ($jobsByStage === []) {
            throw new InvalidArgumentException(
                'local: no jobs to run. The pipeline is empty, or every job is a deploy (pass --include-deploy).'
            );
        }

        $requestedStage = $settings['defaultStage'] ?? null;
        $defaultStage = is_string($requestedStage) && $requestedStage !== ''
            ? $requestedStage
            : (isset($jobsByStage['test']) ? 'test' : (string) array_key_first($jobsByStage));
        if (! isset($jobsByStage[$defaultStage])) {
            throw new InvalidArgumentException(
                "local: stage [{$defaultStage}] is not runnable. Available: " . implode(', ', array_keys($jobsByStage)) . '.'
            );
        }

        $requestedPhp = $settings['defaultPhp'] ?? null;
        $defaultPhp = is_string($requestedPhp) && $requestedPhp !== ''
            ? $requestedPhp
            : $this->newestPhp($jobsByStage);
        $image = $this->stringOption($driver, $options, 'image', 'php:{php}-cli');
        $shellImage = $this->stringOption($driver, $options, 'shell_image', 'alpine:3.22');
        $bootstrap = $driver === 'github' ? null : ($options['bootstrap'] ?? null);
        if ($bootstrap !== null && (! is_array($bootstrap) || ! array_is_list($bootstrap))) {
            throw new InvalidArgumentException("{$driver}: option [bootstrap] must be a list of shell lines.");
        }

        $serviceNames = $this->serviceNames($jobsByStage);
        $functions = [];
        foreach ($jobsByStage as $jobs) {
            foreach ($jobs as $job) {
                $functions[$job->id] = $this->functionName($job->id, array_values($functions));
            }
        }

        $lines = [];
        $lines[] = '#!/usr/bin/env bash';
        $lines[] = '#';
        $lines[] = "# Generated by Slipway for local pipeline runs ({$driver}).";
        $lines[] = '# Secrets are read from .env at runtime and never written into this file.';
        if ($driver === 'github') {
            $lines[] = '# GitHub CI uses setup-php and actions/checkout; this script runs the same';
            $lines[] = '# steps in a php-cli container instead.';
        }
        $lines[] = '#';
        $lines[] = '#   ./ci-local.sh                    # ' . $defaultStage . ' on PHP ' . $defaultPhp;
        $lines[] = '#   ./ci-local.sh ' . $defaultStage . ' ' . $defaultPhp;
        $lines[] = '#   ./ci-local.sh --clean            # detached worktree of HEAD';
        $lines[] = '#   ./ci-local.sh ' . $defaultStage . ' ' . $defaultPhp . ' --clean';
        foreach (array_keys($jobsByStage) as $stage) {
            if ($stage !== $defaultStage) {
                $lines[] = '#   ./ci-local.sh ' . $stage;
            }
        }
        $lines[] = '#';
        $lines[] = 'set -euo pipefail';
        $lines[] = '';
        $lines[] = $this->argumentParsing($defaultStage, $defaultPhp);
        $lines[] = 'MEMORY="${CI_MEMORY:-4g}"';
        $lines[] = 'ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"';
        $lines[] = 'SOURCE="$ROOT"';
        $lines[] = 'WORKTREE=""';
        $lines[] = 'RUN_ID="slipway-$$"';
        $lines[] = 'PAUSE_NAME="${RUN_ID}-pause"';
        $lines[] = 'NETWORK_NAME="${RUN_ID}-net"';
        $lines[] = 'JOB_SCRIPT="$(mktemp)"';
        $lines[] = 'SECRETS_ENV="$(mktemp)"';
        $lines[] = 'chmod 600 "$SECRETS_ENV"';
        $lines[] = 'USE_SECRETS=0';
        $lines[] = '';
        $lines[] = 'reset_runtime() {';
        $lines[] = '  docker rm -f "$PAUSE_NAME"' . $this->serviceRmArgs($serviceNames) . ' >/dev/null 2>&1 || true';
        $lines[] = '  docker network rm "$NETWORK_NAME" >/dev/null 2>&1 || true';
        $lines[] = '}';
        $lines[] = '';
        $lines[] = 'cleanup() {';
        $lines[] = '  reset_runtime';
        $lines[] = '  rm -f "$JOB_SCRIPT" "$SECRETS_ENV"';
        $lines[] = '  if [ -n "${WORKTREE:-}" ]; then';
        $lines[] = '    if [ -d "$WORKTREE" ]; then';
        $lines[] = '      git -C "$ROOT" worktree remove --force "$WORKTREE" >/dev/null 2>&1 || rm -rf "$WORKTREE"';
        $lines[] = '    fi';
        $lines[] = '    git -C "$ROOT" worktree prune >/dev/null 2>&1 || true';
        $lines[] = '  fi';
        $lines[] = '}';
        $lines[] = 'trap cleanup EXIT';
        $lines[] = '';
        $lines[] = $this->selectSource();
        $lines[] = '';
        $lines[] = 'if ! docker info >/dev/null 2>&1; then';
        $lines[] = '  echo "Docker is not running." >&2';
        $lines[] = '  exit 1';
        $lines[] = 'fi';
        $lines[] = '';
        $lines[] = $this->loadSecretsFunction();
        $lines[] = '';

        foreach ($jobsByStage as $jobs) {
            foreach ($jobs as $job) {
                $lines[] = $this->jobFunction(
                    $functions[$job->id],
                    $job,
                    $driver,
                    $image,
                    $shellImage,
                    $bootstrap,
                    $raw,
                );
                $lines[] = '';
            }
        }

        $stageNames = implode('|', array_keys($jobsByStage));
        $usageStages = implode('|', array_keys($jobsByStage));
        $lines[] = 'case "$STAGE" in';
        $lines[] = "  {$stageNames}) ;;";
        $lines[] = '  *)';
        $lines[] = '    echo "Usage: $0 [' . $usageStages . '] [php-version] [--clean]" >&2';
        $lines[] = '    exit 1';
        $lines[] = '    ;;';
        $lines[] = 'esac';
        $lines[] = '';
        $lines[] = 'case "$STAGE" in';
        foreach ($jobsByStage as $stage => $jobs) {
            $calls = [];
            $secretNames = $this->secretNames($jobs);
            if ($secretNames !== []) {
                $quoted = implode(' ', array_map(static fn (string $name): string => Shell::quote($name), $secretNames));
                $calls[] = "    load_secrets {$quoted}";
            }
            foreach ($jobs as $job) {
                $calls[] = '    ' . $functions[$job->id];
            }
            $lines[] = "  {$stage})";
            array_push($lines, ...$calls);
            $lines[] = '    ;;';
        }
        $lines[] = 'esac';

        return implode("\n", $lines) . "\n";
    }

    /**
     * Stage names that a local run can execute (deploy jobs omitted unless requested).
     *
     * @return list<string>
     */
    public function runnableStageNames(Pipeline $pipeline, bool $includeDeploy = false): array
    {
        return array_keys($this->runnableJobsByStage($pipeline, $includeDeploy));
    }

    /**
     * @param  array<string,list<Job>>  $jobsByStage
     * @return array<string,list<Job>>
     */
    private function runnableJobsByStage(Pipeline $pipeline, bool $includeDeploy): array
    {
        $out = [];
        foreach ($pipeline->stages() as $stage => $jobs) {
            foreach ($jobs as $job) {
                if (! $includeDeploy && $job->environment !== null) {
                    continue;
                }
                $out[$stage][] = $job;
            }
        }

        return $out;
    }

    /**
     * @param  array<string,list<Job>>  $jobsByStage
     */
    private function newestPhp(array $jobsByStage): string
    {
        $versions = [];
        foreach ($jobsByStage as $jobs) {
            foreach ($jobs as $job) {
                foreach ($job->phpVersions as $version) {
                    $versions[] = $version;
                }
            }
        }

        if ($versions === []) {
            return '8.3';
        }

        usort($versions, static fn (string $a, string $b): int => version_compare($a, $b));

        return $versions[array_key_last($versions)];
    }

    /**
     * @param  array<string,list<Job>>  $jobsByStage
     * @return list<string>
     */
    private function serviceNames(array $jobsByStage): array
    {
        $names = [];
        foreach ($jobsByStage as $jobs) {
            foreach ($jobs as $job) {
                foreach ($job->services as $service) {
                    $names[$service->name] = true;
                }
            }
        }
        $out = array_keys($names);
        sort($out);

        return $out;
    }

    /** @param list<string> $names */
    private function serviceRmArgs(array $names): string
    {
        $args = '';
        foreach ($names as $name) {
            $args .= ' "${RUN_ID}-' . $name . '"';
        }

        return $args;
    }

    /** @param list<Job> $jobs @return list<string> */
    private function secretNames(array $jobs): array
    {
        $names = [];
        foreach ($jobs as $job) {
            foreach ($job->secretNames() as $name) {
                $names[$name] = true;
            }
        }
        $out = array_keys($names);
        sort($out);

        return $out;
    }

    /** @param list<string> $used */
    private function functionName(string $jobId, array $used): string
    {
        $base = 'run_job_' . preg_replace('/[^A-Za-z0-9_]/', '_', $jobId);
        $name = $base;
        $i = 2;
        while (in_array($name, $used, true)) {
            $name = $base . '_' . $i;
            $i++;
        }

        return $name;
    }

    /**
     * @param  array<string,mixed>  $options
     */
    private function stringOption(string $driver, array $options, string $key, string $default): string
    {
        $value = $options[$key] ?? $default;
        if (! is_string($value) || $value === '') {
            throw new InvalidArgumentException("{$driver}: option [{$key}] must be a non-empty string.");
        }

        return $value;
    }

    private function argumentParsing(string $defaultStage, string $defaultPhp): string
    {
        return <<<SH
CLEAN=0
STAGE=""
PHP_VERSION=""
for arg in "\$@"; do
  case "\$arg" in
    --clean)
      CLEAN=1
      ;;
    --*)
      echo "Unknown option: \$arg" >&2
      echo "Usage: \$0 [stage] [php-version] [--clean]" >&2
      exit 1
      ;;
    *)
      if [ -z "\$STAGE" ]; then
        STAGE="\$arg"
      elif [ -z "\$PHP_VERSION" ]; then
        PHP_VERSION="\$arg"
      fi
      ;;
  esac
done
STAGE="\${STAGE:-{$defaultStage}}"
PHP_VERSION="\${PHP_VERSION:-{$defaultPhp}}"
SH;
    }

    private function selectSource(): string
    {
        return <<<'SH'
if [ "$CLEAN" -eq 1 ]; then
  if ! git -C "$ROOT" rev-parse --verify HEAD >/dev/null 2>&1; then
    echo "Cannot run --clean: this directory has no git HEAD." >&2
    exit 1
  fi
  WORKTREE="$(mktemp -d)"
  rmdir "$WORKTREE"
  git -C "$ROOT" worktree prune >/dev/null 2>&1 || true
  git -C "$ROOT" worktree add --detach "$WORKTREE" HEAD
  SOURCE="$WORKTREE"
  echo "Running against detached HEAD in $WORKTREE."
elif git -C "$ROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  status="$(git -C "$ROOT" status --porcelain 2>/dev/null || true)"
  if [ -n "$status" ]; then
    echo "Warning: uncommitted or untracked files. This local run may not match CI. Pass --clean to run against HEAD." >&2
  fi
fi
SH;
    }

    private function loadSecretsFunction(): string
    {
        return <<<'SH'
load_secrets() {
  if [ "$#" -eq 0 ]; then
    return 0
  fi
  if [ ! -f "$ROOT/.env" ]; then
    echo "Missing $ROOT/.env (needed for secrets: $*)" >&2
    exit 1
  fi
  : > "$SECRETS_ENV"
  chmod 600 "$SECRETS_ENV"
  for name in "$@"; do
    line="$(grep -E "^${name}=" "$ROOT/.env" | tail -n 1 || true)"
    if [ -z "$line" ]; then
      echo "Secret ${name} is not set in .env" >&2
      exit 1
    fi
    key="${line%%=*}"
    val="${line#*=}"
    case "$val" in
      \"*\") val="${val#\"}"; val="${val%\"}" ;;
      \'*\') val="${val#\'}"; val="${val%\'}" ;;
    esac
    printf '%s=%s\n' "$key" "$val" >> "$SECRETS_ENV"
  done
  USE_SECRETS=1
}
SH;
    }

    /**
     * @param  list<string>|null  $bootstrap
     * @param  array<string,mixed>  $raw
     */
    private function jobFunction(
        string $fn,
        Job $job,
        string $driver,
        string $image,
        string $shellImage,
        ?array $bootstrap,
        array $raw,
    ): string {
        if ($job->services !== [] && ! $job->needsPhp()) {
            throw new InvalidArgumentException(
                "local: job [{$job->id}] uses services but has no PHP runtime to wait for them."
            );
        }

        $body = $this->containerScript($job, $driver, $bootstrap);
        $delimiter = $this->heredocDelimiter($body);
        $gitlab = $driver === 'gitlab';
        $hasSecrets = $job->secretNames() !== [];
        $dockerImage = $job->needsPhp() ? $this->bashImage($image) : $this->bashImage($shellImage);
        $lines = [];
        $lines[] = "{$fn}() {";
        $lines[] = '  reset_runtime';
        $lines[] = '  echo "Running job ' . $job->id . '..."';

        if ($job->services !== []) {
            if ($gitlab) {
                $lines[] = '  docker network create "$NETWORK_NAME" >/dev/null';
                foreach ($job->services as $service) {
                    $lines[] = $this->indent($this->startService($job, $service, $driver, $raw, gitlab: true), 2);
                }
            } else {
                $lines[] = '  docker run -d --name "$PAUSE_NAME" ' . Shell::quote(self::PAUSE_IMAGE) . ' tail -f /dev/null >/dev/null';
                foreach ($job->services as $service) {
                    $lines[] = $this->indent($this->startService($job, $service, $driver, $raw, gitlab: false), 2);
                }
            }
        }

        $lines[] = "  cat >\"\$JOB_SCRIPT\" <<'{$delimiter}'";
        $lines[] = rtrim($body, "\n");
        $lines[] = $delimiter;

        $network = '';
        if ($job->services !== []) {
            $network = $gitlab
                ? ' --network "$NETWORK_NAME"'
                : ' --network container:"$PAUSE_NAME"';
        }
        $envFile = $hasSecrets ? ' --env-file "$SECRETS_ENV"' : '';

        $lines[] = '  docker run --rm --memory="$MEMORY"' . $network . $envFile . ' \\';
        $lines[] = '    -v "$SOURCE":/src:ro -v "$JOB_SCRIPT":/ci.sh:ro \\';
        $lines[] = '    ' . $dockerImage . ' sh /ci.sh';
        $lines[] = '}';

        return implode("\n", $lines);
    }

    /**
     * @param  list<string>|null  $bootstrap
     */
    private function containerScript(Job $job, string $driver, ?array $bootstrap): string
    {
        $parts = ['set -e'];
        $parts[] = $this->rsyncInstall($job->needsPhp());
        $setup = $this->containerSetup($job, $driver, $bootstrap);
        if ($setup !== '') {
            $parts[] = rtrim($setup, "\n");
        }
        $parts[] = $this->copySource();

        if ($job->services !== []) {
            if ($driver === 'gitlab') {
                foreach ($job->services as $service) {
                    $parts[] = rtrim($this->waitForPorts($service->ports, $service->name), "\n");
                }
            } else {
                $ports = [];
                foreach ($job->services as $service) {
                    foreach ($service->ports as $port) {
                        $ports[] = $port;
                    }
                }
                $parts[] = rtrim($this->waitForPorts($ports, '127.0.0.1'), "\n");
            }
        }

        $env = $this->jobEnv($job, $driver);
        if ($env !== []) {
            $parts[] = $this->shellExports($env);
        }

        $success = [];
        $failure = [];
        $always = [];
        foreach ($job->steps as $step) {
            if ($step->type !== StepType::Run) {
                continue;
            }
            $block = $this->stepBlock($step);
            if ($step->runOn === 'failure') {
                $failure[] = $block;
            } elseif ($step->runOn === 'always') {
                $always[] = $block;
            } else {
                $success[] = $block;
            }
        }

        if ($failure === [] && $always === []) {
            array_push($parts, ...$success);

            return implode("\n", array_filter($parts, static fn (string $p): bool => $p !== '')) . "\n";
        }

        $parts[] = 'set +e';
        $parts[] = '(';
        $parts[] = '  set -e';
        foreach ($success as $block) {
            $parts[] = $this->indent($block, 2);
        }
        $parts[] = ')';
        $parts[] = 'status=$?';
        $parts[] = 'set -e';
        if ($failure !== []) {
            $parts[] = 'if [ "$status" -ne 0 ]; then';
            $parts[] = '  set +e';
            foreach ($failure as $block) {
                $parts[] = $this->indent($block, 2);
            }
            $parts[] = '  set -e';
            $parts[] = 'fi';
        }
        foreach ($always as $block) {
            $parts[] = 'set +e';
            $parts[] = $block;
            $parts[] = 'set -e';
        }
        $parts[] = 'exit "$status"';

        return implode("\n", array_filter($parts, static fn (string $p): bool => $p !== '')) . "\n";
    }

    private function stepBlock(Step $step): string
    {
        $name = str_replace(["\r", "\n"], ' ', $step->name);
        $body = $this->failFast(($step->env !== [] ? $this->shellExports($step->env) . "\n" : '') . rtrim((string) $step->run, "\n"));

        return '# ' . $name . "\n" . rtrim($body, "\n");
    }

    /**
     * @param  list<string>|null  $bootstrap
     */
    private function containerSetup(Job $job, string $driver, ?array $bootstrap): string
    {
        if ($bootstrap !== null) {
            $lines = [];
            foreach ($bootstrap as $line) {
                if (! is_string($line)) {
                    throw new InvalidArgumentException("{$driver}: option [bootstrap] must be a list of shell lines.");
                }
                $lines[] = $line;
            }

            return $lines === [] ? '' : $this->failFast(implode("\n", $lines));
        }

        if ($job->needsPhp()) {
            try {
                $lines = [PhpBootstrap::script($job->extensions, $job->coverage, PhpBootstrap::aptPackagesFor($job->tools))];
            } catch (InvalidArgumentException $e) {
                throw new InvalidArgumentException(
                    'local: ' . $e->getMessage() . ' Local runs use a php-cli image. Use a container driver (bitbucket, gitlab, circleci) with a custom bootstrap, or drop the unknown extension.'
                );
            }
            if ($job->node !== null) {
                $lines[] = PhpBootstrap::nodeInstall($job->node);
            }
            if ($job->bun !== null) {
                $lines[] = PhpBootstrap::bunInstall($job->bun);
            }

            return $this->failFast(implode("\n", $lines));
        }

        if ($job->tools !== []) {
            return $this->failFast(PhpBootstrap::alpineScript($job->tools));
        }

        return '';
    }

    private function rsyncInstall(bool $debian): string
    {
        if ($debian) {
            return "apt-get update -qq\napt-get install -y -qq --no-install-recommends rsync";
        }

        return 'apk add --no-cache rsync';
    }

    private function copySource(): string
    {
        return <<<'SH'
mkdir -p /build
rsync -a --exclude .git --exclude vendor --exclude node_modules --exclude '.env*' --exclude storage/logs /src/ /build/
cd /build
if [ -f /src/.env.example ]; then cp /src/.env.example .env.example; fi
SH;
    }

    /**
     * @param  array<string,mixed>  $raw
     */
    private function startService(Job $job, Service $service, string $driver, array $raw, bool $gitlab): string
    {
        $image = $this->serviceImage($driver, $job, $service, $raw);
        $name = '"${RUN_ID}-' . $service->name . '"';
        $network = $gitlab
            ? '--network "$NETWORK_NAME" --network-alias ' . Shell::quote($service->name)
            : '--network container:"$PAUSE_NAME"';

        $envFlags = '';
        foreach ($service->env as $key => $value) {
            $envFlags .= ' -e ' . Shell::quote($key . '=' . $value);
        }

        return 'echo "Starting ' . $service->name . ' (' . $image . ')..."' . "\n"
            . 'docker run -d --name ' . $name . ' ' . $network . $envFlags . ' ' . Shell::quote($image) . ' >/dev/null';
    }

    /**
     * @param  array<string,mixed>  $raw
     */
    private function serviceImage(string $driver, Job $job, Service $service, array $raw): string
    {
        $overlay = match ($driver) {
            'bitbucket' => $this->dig($raw, ['definitions', 'services', $service->name, 'image']),
            'github' => $this->githubServiceImage($raw, $job->id, $service->name),
            'gitlab' => $this->gitlabServiceImage($raw, $job->id, $service->name),
            'circleci' => $this->circleServiceImage($raw, $job->id, $service->name),
            default => null,
        };

        return is_string($overlay) && $overlay !== '' ? $overlay : $service->image;
    }

    /** @param array<string,mixed> $raw */
    private function githubServiceImage(array $raw, string $jobId, string $serviceName): ?string
    {
        $direct = $this->dig($raw, ['jobs', $jobId, 'services', $serviceName, 'image']);
        if (is_string($direct) && $direct !== '') {
            return $direct;
        }

        foreach ($raw['jobs'] ?? [] as $job) {
            if (! is_array($job)) {
                continue;
            }
            $image = $job['services'][$serviceName]['image'] ?? null;
            if (is_string($image) && $image !== '') {
                return $image;
            }
        }

        return null;
    }

    /** @param array<string,mixed> $raw */
    private function gitlabServiceImage(array $raw, string $jobId, string $serviceName): ?string
    {
        $fromJob = $this->gitlabServicesList($raw[$jobId]['services'] ?? null, $serviceName);
        if ($fromJob !== null) {
            return $fromJob;
        }

        foreach ($raw as $block) {
            if (! is_array($block)) {
                continue;
            }
            $found = $this->gitlabServicesList($block['services'] ?? null, $serviceName);
            if ($found !== null) {
                return $found;
            }
        }

        return null;
    }

    private function gitlabServicesList(mixed $services, string $serviceName): ?string
    {
        if (! is_array($services)) {
            return null;
        }

        foreach ($services as $entry) {
            if (is_string($entry) && (str_starts_with($entry, $serviceName . ':') || $entry === $serviceName)) {
                return $entry;
            }
            if (! is_array($entry)) {
                continue;
            }
            $alias = $entry['alias'] ?? null;
            $name = $entry['name'] ?? null;
            if ($alias === $serviceName && is_string($name) && $name !== '') {
                return $name;
            }
            if (is_string($name) && str_starts_with($name, $serviceName . ':')) {
                return $name;
            }
        }

        return null;
    }

    /** @param array<string,mixed> $raw */
    private function circleServiceImage(array $raw, string $jobId, string $serviceName): ?string
    {
        $lists = [];
        $direct = $this->dig($raw, ['jobs', $jobId, 'docker']);
        if (is_array($direct)) {
            $lists[] = $direct;
        }
        foreach ($raw['jobs'] ?? [] as $job) {
            if (is_array($job) && isset($job['docker']) && is_array($job['docker'])) {
                $lists[] = $job['docker'];
            }
        }

        foreach ($lists as $docker) {
            foreach ($docker as $container) {
                if (! is_array($container)) {
                    continue;
                }
                $image = $container['image'] ?? null;
                if (! is_string($image) || $image === '') {
                    continue;
                }
                if (str_starts_with($image, $serviceName . ':') || str_contains($image, '/' . $serviceName . ':')) {
                    return $image;
                }
            }
        }

        return null;
    }

    /** @param list<string|int> $path */
    private function dig(array $data, array $path): mixed
    {
        $cursor = $data;
        foreach ($path as $key) {
            if (! is_array($cursor) || ! array_key_exists($key, $cursor)) {
                return null;
            }
            $cursor = $cursor[$key];
        }

        return $cursor;
    }

    /** @return array<string,string> */
    private function jobEnv(Job $job, string $driver): array
    {
        $env = $job->env;
        foreach ($job->services as $service) {
            $host = $driver === 'gitlab' ? $service->name : '127.0.0.1';
            foreach ($service->appEnv as $name => $value) {
                $env[$name] = str_replace('{host}', $host, $value);
            }
        }

        return $env;
    }

    private function bashImage(string $template): string
    {
        if (str_contains($template, '{php}')) {
            return '"' . str_replace('{php}', '${PHP_VERSION}', $template) . '"';
        }

        return Shell::quote($template);
    }

    private function heredocDelimiter(string $body): string
    {
        $delimiter = 'SLIPWAY_JOB';
        $i = 0;
        while (preg_match('/^' . preg_quote($delimiter, '/') . '$/m', $body) === 1) {
            $i++;
            $delimiter = 'SLIPWAY_JOB_' . $i;
        }

        return $delimiter;
    }

    /** @param array<string,string> $env */
    private function shellExports(array $env): string
    {
        $lines = [];
        foreach ($env as $name => $value) {
            $lines[] = 'export ' . $name . '=' . Shell::quote($value);
        }

        return implode("\n", $lines);
    }

    /** @param list<int> $ports */
    private function waitForPorts(array $ports, string $host): string
    {
        if ($ports === []) {
            return '';
        }

        $template = <<<'SH'
for port in __PORTS__; do
  tries=0
  until php -r 'exit(@fsockopen($argv[1], (int) $argv[2]) ? 0 : 1);' __HOST__ "$port"; do
    tries=$((tries + 1))
    if [ "$tries" -ge 60 ]; then
      echo "Service on port $port did not start in time" >&2
      exit 1
    fi
    sleep 1
  done
done
SH;

        return strtr($template, ['__PORTS__' => implode(' ', $ports), '__HOST__' => Shell::quote($host)]) . "\n";
    }

    private function failFast(string $script): string
    {
        $script = rtrim($script, "\n");

        if ($script === '' || ! str_contains($script, "\n") || preg_match('/^\s*set\s+-[a-z]*e/', $script) === 1) {
            return $script . "\n";
        }

        return "set -e\n" . $script . "\n";
    }

    private function indent(string $script, int $spaces): string
    {
        return Shell::indent($script, $spaces);
    }
