<?php

declare(strict_types=1);

namespace Usamamuneerchaudhary\Slipway\Tests\Unit;

use PHPUnit\Framework\TestCase;
use RuntimeException;
use Usamamuneerchaudhary\Slipway\Config\ConfigException;
use Usamamuneerchaudhary\Slipway\Slipway;
use Usamamuneerchaudhary\Slipway\Tests\Support\Fixture;

final class CompilerTest extends TestCase
{
    private string $dir;

    protected function setUp(): void
    {
        $this->dir = Fixture::tempDir();
    }

    protected function tearDown(): void
    {
        Fixture::remove($this->dir);
    }

    private function errorsOf(array $config): string
    {
        try {
            Fixture::compile($config);
        } catch (ConfigException $e) {
            return implode("\n", $e->errors);
        }

        $this->fail('Expected compilation to fail.');
    }

    public function test_it_produces_one_file_per_enabled_driver_with_default_paths(): void
    {
        $result = Fixture::compile(Fixture::full());

        $this->assertSame(['github', 'bitbucket', 'gitlab'], array_keys($result->files));
        $this->assertSame('.github/workflows/slipway.yml', $result->files['github']->path);
        $this->assertSame('bitbucket-pipelines.yml', $result->files['bitbucket']->path);
        $this->assertSame('.gitlab-ci.yml', $result->files['gitlab']->path);
    }

    public function test_disabled_drivers_produce_nothing(): void
    {
        $result = Fixture::compile(Fixture::minimal(['drivers' => ['github' => true, 'gitlab' => false]]));

        $this->assertSame(['github'], array_keys($result->files));
    }

    public function test_output_path_can_be_overridden(): void
    {
        $result = Fixture::compile(Fixture::minimal(['drivers' => ['github' => ['path' => '.github/workflows/ci.yml']]]));

        $this->assertSame('.github/workflows/ci.yml', $result->files['github']->path);
    }

    public function test_header_marks_files_as_generated_and_names_the_source(): void
    {
        $contents = Fixture::compile(Fixture::minimal())->files['github']->contents;

        $this->assertStringStartsWith('# Generated by Slipway for GitHub Actions. DO NOT EDIT BY HAND.', $contents);
        $this->assertStringContainsString('# Source: config/slipway.php (config hash ', $contents);
        $this->assertStringContainsString('slipway:compile', $contents);
    }

    public function test_pest_tia_writes_a_github_baseline_workflow_without_changing_the_test_job(): void
    {
        $result = Fixture::compile(Fixture::minimal([
            'php' => ['8.3', '8.4'],
            'stages' => ['test' => ['pest' => ['tia' => true]]],
        ]));

        $this->assertArrayHasKey('tia-baseline', $result->files);
        $this->assertSame('.github/workflows/tia-baseline.yml', $result->files['tia-baseline']->path);
        $tia = $result->files['tia-baseline']->contents;
        $this->assertStringContainsString('name: TIA Baseline', $tia);
        $this->assertStringContainsString('pest-tia-baseline', $tia);
        $this->assertStringContainsString('include-hidden-files: true', $tia);
        $this->assertStringContainsString('vendor/bin/pest --tia --coverage --fresh', $tia);
        $this->assertStringNotContainsString('--parallel', $tia);
        $this->assertStringContainsString('php-version: "8.4"', $tia);
        $this->assertStringContainsString('coverage: xdebug', $tia);
        $this->assertStringContainsString('fetch-depth: 0', $tia);
        $this->assertStringNotContainsString('--tia', $result->files['github']->contents);
        $this->assertStringContainsString('vendor/bin/pest', $result->files['github']->contents);
    }

    public function test_pest_tia_without_github_warns_and_writes_no_baseline_file(): void
    {
        $result = Fixture::compile(Fixture::minimal([
            'drivers' => ['gitlab' => true],
            'stages' => ['test' => ['pest' => ['tia' => true]]],
        ]));

        $this->assertArrayNotHasKey('tia-baseline', $result->files);
        $this->assertStringContainsString('GitHub-only', implode("\n", $result->warnings));
    }

    public function test_conflicting_pest_tia_options_fail_compilation(): void
    {
        $this->assertStringContainsString('tia', $this->errorsOf(Fixture::minimal([
            'php' => ['8.3', '8.4'],
            'stages' => [
                'unit' => ['pest' => ['tia' => true]],
                'browser' => ['pest' => ['tia' => ['php' => '8.3']]],
            ],
        ])));
    }

    public function test_the_package_version_never_appears_in_generated_output(): void
    {
        foreach (Fixture::compile(Fixture::full())->files as $file) {
            $this->assertStringNotContainsString(Slipway::VERSION, $file->contents);
        }
    }

    public function test_strict_mode_warns_about_actions_that_are_not_pinned_to_a_commit(): void
    {
        $warnings = implode("\n", Fixture::compile(Fixture::minimal(['strict' => true]))->warnings);

        $this->assertStringContainsString('actions/checkout', $warnings);
        $this->assertStringContainsString('slipway:pin', $warnings);
    }

    public function test_the_pin_warning_is_for_strict_mode_only_and_disappears_once_pinned(): void
    {
        $this->assertStringNotContainsString('slipway:pin', implode("\n", Fixture::compile(Fixture::minimal())->warnings));

        $sha = str_repeat('c3', 20);
        $pins = ['actions/checkout' => $sha, 'actions/cache' => $sha, 'shivammathur/setup-php' => $sha, 'actions/setup-node' => $sha, 'actions/upload-artifact' => $sha, 'actions/download-artifact' => $sha];
        $pinned = Fixture::compile(Fixture::minimal(['strict' => true, 'drivers' => ['github' => ['options' => ['pins' => $pins]]]]));

        $this->assertStringNotContainsString('slipway:pin', implode("\n", $pinned->warnings));
    }

    public function test_drift_ignores_windows_line_endings(): void
    {
        $compiler = Fixture::compiler();
        $result = $compiler->compile(Fixture::minimal());
        $compiler->write($result, $this->dir);

        $target = $this->dir . '/.github/workflows/slipway.yml';
        file_put_contents($target, str_replace("\n", "\r\n", (string) file_get_contents($target)));

        $this->assertSame([], $compiler->drift($result, $this->dir));
    }

    public function test_credential_findings_are_reported_together_with_schema_errors(): void
    {
        $token = 'ghp_' . str_repeat('aB3dE6', 7);
        $errors = $this->errorsOf(Fixture::minimal(['name' => 'Token ' . $token, 'bogus_key' => true]));

        $this->assertStringContainsString('Credential in configuration', $errors);
        $this->assertStringContainsString('bogus_key', $errors);
    }

    public function test_source_label_can_be_overridden_per_compile(): void
    {
        $result = Fixture::compiler()->compile(Fixture::minimal(), 'slipway.php');

        $this->assertStringContainsString('# Source: slipway.php', $result->files['github']->contents);
    }

    public function test_output_is_byte_for_byte_deterministic(): void
    {
        $a = Fixture::compile(Fixture::full());
        $b = Fixture::compile(Fixture::full());

        foreach ($a->files as $name => $file) {
            $this->assertSame($file->contents, $b->files[$name]->contents);
        }
        $this->assertSame($a->configHash, $b->configHash);
    }

    public function test_config_hash_changes_when_the_config_changes(): void
    {
        $a = Fixture::compile(Fixture::minimal());
        $b = Fixture::compile(Fixture::minimal(['name' => 'Other']));

        $this->assertNotSame($a->configHash, $b->configHash);
    }

    public function test_write_creates_files_and_directories_and_reports_changes(): void
    {
        $compiler = Fixture::compiler();
        $result = $compiler->compile(Fixture::minimal());

        $changed = $compiler->write($result, $this->dir);

        $this->assertSame(['.github/workflows/slipway.yml'], $changed);
        $this->assertFileExists($this->dir . '/.github/workflows/slipway.yml');
        $this->assertSame($result->files['github']->contents, file_get_contents($this->dir . '/.github/workflows/slipway.yml'));
    }

    public function test_write_is_idempotent(): void
    {
        $compiler = Fixture::compiler();
        $result = $compiler->compile(Fixture::minimal());
        $compiler->write($result, $this->dir);

        $this->assertSame([], $compiler->write($result, $this->dir));
    }

    public function test_drift_detects_missing_and_modified_files(): void
    {
        $compiler = Fixture::compiler();
        $result = $compiler->compile(Fixture::minimal());

        $this->assertSame(['.github/workflows/slipway.yml' => 'missing'], $compiler->drift($result, $this->dir));

        $compiler->write($result, $this->dir);
        $this->assertSame([], $compiler->drift($result, $this->dir));

        file_put_contents($this->dir . '/.github/workflows/slipway.yml', "# hand edit\n", FILE_APPEND);
        $this->assertSame(['.github/workflows/slipway.yml' => 'modified'], $compiler->drift($result, $this->dir));
    }

    public function test_drift_is_detected_when_the_config_changes(): void
    {
        $compiler = Fixture::compiler();
        $compiler->write($compiler->compile(Fixture::minimal()), $this->dir);

        $changed = $compiler->compile(Fixture::minimal(['php' => ['8.4']]));

        $this->assertSame(['.github/workflows/slipway.yml' => 'modified'], $compiler->drift($changed, $this->dir));
    }

    public function test_two_drivers_cannot_write_the_same_file(): void
    {
        $errors = $this->errorsOf(Fixture::minimal(['drivers' => [
            'github' => ['path' => 'ci.yml'],
            'gitlab' => ['path' => 'ci.yml'],
        ]]));

        $this->assertStringContainsString('would both write ci.yml', $errors);
    }

    public function test_unknown_driver_is_reported_with_available_ones(): void
    {
        $errors = $this->errorsOf(Fixture::minimal(['drivers' => ['jenkins' => true]]));

        $this->assertStringContainsString('no such driver', $errors);
        $this->assertStringContainsString('github', $errors);
    }

    public function test_at_least_one_driver_must_be_enabled(): void
    {
        $this->assertStringContainsString('no driver is enabled', $this->errorsOf(Fixture::minimal(['drivers' => ['github' => false]])));
    }

    public function test_unsupported_features_warn_by_default(): void
    {
        $result = Fixture::compile(Fixture::minimal([
            'drivers' => ['bitbucket' => true],
            'triggers' => ['push' => ['main'], 'paths_ignore' => ['docs/**']],
        ]));

        $this->assertStringContainsString('Path filters is not supported', implode("\n", $result->warnings));
    }

    public function test_strict_mode_turns_unsupported_features_into_errors(): void
    {
        $errors = $this->errorsOf(Fixture::minimal([
            'strict' => true,
            'drivers' => ['bitbucket' => true],
            'triggers' => ['push' => ['main'], 'paths_ignore' => ['docs/**']],
        ]));

        $this->assertStringContainsString('(strict mode)', $errors);
    }

    public function test_partially_supported_features_only_warn_even_in_strict_mode(): void
    {
        $result = Fixture::compile(Fixture::full(['strict' => true, 'drivers' => ['github' => true], 'triggers' => ['push' => ['main'], 'pull_request' => true]]));

        $this->assertStringContainsString('partially supported', implode("\n", $result->warnings));
    }

    public function test_credentials_in_the_config_are_rejected_without_echoing_them(): void
    {
        $token = 'ghp_' . str_repeat('aB3dE6', 7);
        $errors = $this->errorsOf(Fixture::minimal(['env' => ['NOTE' => "see {$token}"]]));

        $this->assertStringContainsString('GitHub token', $errors);
        $this->assertStringNotContainsString($token, $errors);
    }

    public function test_literal_values_for_sensitive_variables_are_rejected(): void
    {
        $errors = $this->errorsOf(Fixture::minimal(['env' => ['DB_PASSWORD' => 'hunter2']]));

        $this->assertStringContainsString('Literal value for sensitive variable', $errors);
        $this->assertStringNotContainsString('hunter2', $errors);
    }

    public function test_policy_violations_fail_compilation(): void
    {
        $errors = $this->errorsOf(Fixture::minimal(['policies' => ['tests-before-deploy'], 'stages' => ['qa' => ['pint'], 'build' => ['build-artifact']],
            'environments' => ['s' => ['branch' => 'main', 'via' => 'ssh', 'options' => ['host' => 'a.test', 'user' => 'd', 'path' => '/srv/a']]],
            'secrets' => ['SSH_PRIVATE_KEY', 'SSH_KNOWN_HOSTS']]));

        $this->assertStringContainsString('tests-before-deploy', $errors);
    }

    public function test_undeclared_secrets_fail_compilation(): void
    {
        $config = Fixture::full();
        $config['secrets'] = ['SSH_PRIVATE_KEY'];

        $this->assertStringContainsString('Secret [SSH_KNOWN_HOSTS] is used by the pipeline but not declared', $this->errorsOf($config));
    }

    public function test_unused_declared_secrets_only_warn(): void
    {
        $result = Fixture::compile(Fixture::minimal(['secrets' => ['NEVER_USED']]));

        $this->assertStringContainsString('declared but never used', implode("\n", $result->warnings));
    }

    public function test_raw_overrides_are_merged_into_the_output(): void
    {
        $result = Fixture::compile(Fixture::minimal(['drivers' => ['github' => ['raw' => ['permissions' => ['contents' => 'read', 'pull-requests' => 'write']]]]]));

        $this->assertStringContainsString('pull-requests: write', $result->files['github']->contents);
    }

    public function test_write_refuses_paths_that_escape_the_project(): void
    {
        $compiler = Fixture::compiler();
        $result = $compiler->compile(Fixture::minimal());
        $evil = new \Usamamuneerchaudhary\Slipway\CompileResult(
            $result->pipeline,
            ['github' => new \Usamamuneerchaudhary\Slipway\GeneratedFile('github', '../escape.yml', 'x')],
            [],
            'x',
        );

        $this->expectException(RuntimeException::class);
        $this->expectExceptionMessage('outside the project');

        $compiler->write($evil, $this->dir);
    }

    public function test_pest_tia_baseline_parallel_follows_the_pest_step(): void
    {
        $following = Fixture::compile(Fixture::minimal([
            'stages' => ['test' => ['pest' => ['parallel' => true, 'tia' => true]]],
        ]));

        $this->assertStringContainsString(
            'vendor/bin/pest --parallel --tia --coverage --fresh',
            $following->files['tia-baseline']->contents,
        );
        $this->assertStringNotContainsString('tia.parallel', implode("\n", $following->warnings));

        $explicit = Fixture::compile(Fixture::minimal([
            'stages' => ['test' => ['pest' => ['tia' => ['parallel' => true]]]],
        ]));

        $this->assertStringContainsString(
            'vendor/bin/pest --parallel --tia --coverage --fresh',
            $explicit->files['tia-baseline']->contents,
        );
        $this->assertStringContainsString('No Pest step in this pipeline does', implode("\n", $explicit->warnings));
    }

    public function test_vite_preset_without_a_script_warns_that_it_runs_npx_vite_build(): void
    {
        $result = Fixture::compile(Fixture::minimal([
            'node' => '22',
            'stages' => ['build' => ['build-assets' => ['preset' => 'vite']]],
        ]));

        $warnings = implode("\n", $result->warnings);
        $this->assertStringContainsString('npx vite build', $warnings);
        $this->assertStringContainsString('package.json script', $warnings);
        $this->assertStringContainsString('npx vite build', $result->files['github']->contents);

        $scripted = Fixture::compile(Fixture::minimal([
            'node' => '22',
            'stages' => ['build' => ['build-assets' => ['preset' => 'vite', 'script' => 'assets']]],
        ]));

        $this->assertStringNotContainsString('npx vite build', implode("\n", $scripted->warnings));
        $this->assertStringContainsString('npm run assets', $scripted->files['github']->contents);
    }
}
